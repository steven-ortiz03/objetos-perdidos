    public FrmEntrega(ObjetoPerdido objeto) {
        this.objeto = objeto;
        initComponents();
        Tema.estilizarBoton(btnCancelar);
        Tema.estilizarBoton(btnConfirmar);
        if (objeto != null) {
            mostrarResumen();
        }
        setLocationRelativeTo(null);
    }

    /** Resumen del objeto que se entrega. */
    private void mostrarResumen() {
        lblObjeto.setText("Objeto: " + objeto.getNombre() + "  (ID " + objeto.getId() + ")");
        lblResguardo.setText("Resguardado en: " + objeto.getLugarResguardo().getNombre());
        if (Sesion.getUsuario() != null) {
            lblFuncionario.setText("Entrega: " + Sesion.getUsuario().getNombre() + " · fecha actual");
        }
    }

    private void confirmar() {
        if (objeto == null) {
            return; // la ventana se abrió solo para ver el diseño
        }
        try {
            entregaController.registrarEntrega(objeto, txtNombre.getText(),
                    txtDocumento.getText(), txtObservaciones.getText());
            Mensajes.informacion(this, "Entrega registrada. El objeto quedó como Entregado.");
            dispose();
        } catch (Exception error) {
            Mensajes.error(this, error);
        }
    }

